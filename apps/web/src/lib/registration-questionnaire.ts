export type QuestionType = 'section' | 'text' | 'long' | 'date' | 'number' | 'yesno' | 'choice' | 'agree';

export type LinkKind = '' | 'operating' | 'financial' | 'medication' | 'text' | 'url';

export type Question = {
  id: string;
  text: string;
  type: QuestionType;
  help?: string;
  options?: string[];
  linkKind?: LinkKind;
  linkLabel?: string;
  linkUrl?: string;
  document?: string;
};

const id = () => Math.random().toString(36).slice(2, 9);

function schoolYears(now = new Date()) {
  const start = now.getMonth() >= 8 ? now.getFullYear() : now.getFullYear() - 1;
  const label = (year: number) => `${year}-${String(year + 1).slice(2)}`;
  return [label(start), label(start + 1)];
}

function q(partial: Omit<Question, 'id'>): Question {
  return { id: id(), ...partial };
}

