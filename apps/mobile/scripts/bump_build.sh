#!/bin/bash
# Bumps the pubspec build number to YYYYMMDDHHMM and regenerates app_version.dart
# so the login badge always shows a fresh version after each install/run.
set -euo pipefail

cd "$(dirname "$0")/.."
PUBSPEC="pubspec.yaml"
OUT="lib/core/app_version.dart"

line="$(grep -E '^version:' "$PUBSPEC" | head -n1)"
name="$(printf '%s' "$line" | sed -E 's/^version:[[:space:]]*([0-9]+\.[0-9]+\.[0-9]+).*/\1/')"
if [[ -z "$name" ]]; then
  echo "Δεν διάβασα version από το pubspec.yaml" >&2
  exit 1
fi

build="$(date +%Y%m%d%H%M)"
sed -i.bak -E "s/^version:[[:space:]]*.*/version: ${name}+${build}/" "$PUBSPEC"
rm -f "${PUBSPEC}.bak"

cat > "$OUT" <<EOF
/// Auto-generated by scripts/bump_build.sh — do not edit by hand.
const appVersionName = '$name';
const appBuildNumber = '$build';
const appVersionLabel = 'omnedu v${name}+${build}';
EOF

echo "Έκδοση: omnedu v${name}+${build}"
