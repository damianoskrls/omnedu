#!/bin/sh
# Called by: Xcode Cloud immediately before xcodebuild.
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IOS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
MOBILE="$(cd "$IOS_DIR/.." && pwd)"

export PATH="$HOME/flutter/bin:$PATH"
export FLUTTER_ROOT="${FLUTTER_ROOT:-$HOME/flutter}"

if [ ! -x "$FLUTTER_ROOT/bin/flutter" ]; then
  echo "error: Flutter missing at $FLUTTER_ROOT" >&2
  exit 1
fi

flutter config --no-enable-swift-package-manager

cd "$MOBILE"
flutter pub get
flutter build ios --config-only --release --no-codesign

cd "$IOS_DIR"

# App Store Connect requires CFBundleVersion > previous TestFlight uploads.
# Prior iOS builds used YYYYMMDDHHMM (e.g. 202611041506). Android pubspec uses
# shorter YYMMDDHH (e.g. 26110518) which ASC rejects as not increasing.
# Force an iOS-only build number here, after Flutter regenerates Generated.xcconfig.
MIN_IOS_BUILD=202611050000
IOS_BUILD_NUMBER="$(date -u +%Y%m%d%H%M)"
GEN="Flutter/Generated.xcconfig"
test -f "$GEN"

if grep -q '^FLUTTER_BUILD_NUMBER=' "$GEN"; then
  sed -i '' "s/^FLUTTER_BUILD_NUMBER=.*/FLUTTER_BUILD_NUMBER=$IOS_BUILD_NUMBER/" "$GEN"
else
  echo "FLUTTER_BUILD_NUMBER=$IOS_BUILD_NUMBER" >> "$GEN"
fi

# Ensure marketing version is present (from pubspec via flutter config-only).
NAME="$(grep '^FLUTTER_BUILD_NAME=' "$GEN" | cut -d= -f2)"
NUMBER="$(grep '^FLUTTER_BUILD_NUMBER=' "$GEN" | cut -d= -f2)"
echo "ci_pre_xcodebuild: FLUTTER_BUILD_NAME=$NAME"
echo "ci_pre_xcodebuild: FLUTTER_BUILD_NUMBER=$NUMBER"

if [ -z "$NAME" ] || [ -z "$NUMBER" ]; then
  echo "error: missing FLUTTER_BUILD_NAME/NUMBER in $GEN" >&2
  cat "$GEN" >&2
  exit 1
fi
if [ "$NUMBER" -le "$MIN_IOS_BUILD" ]; then
  echo "error: iOS build $NUMBER must be > $MIN_IOS_BUILD (ASC monotonic CFBundleVersion)" >&2
  exit 1
fi

# Also stamp a small xcconfig that forces MARKETING_VERSION for the Runner target.
cat > Flutter/Version.xcconfig <<EOF
// Generated by ci_pre_xcodebuild.sh — do not commit.
MARKETING_VERSION=$NAME
CURRENT_PROJECT_VERSION=$NUMBER
FLUTTER_BUILD_NAME=$NAME
FLUTTER_BUILD_NUMBER=$NUMBER
EOF

pod install

test -f "Pods/Target Support Files/Pods-Runner/Pods-Runner.release.xcconfig"
test -f "Flutter/Generated.xcconfig"
rm -f Flutter/Pods
ln -s ../Pods Flutter/Pods

echo "ci_pre_xcodebuild: ready (will archive $NAME ($NUMBER))"
exit 0
